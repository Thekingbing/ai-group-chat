// Bundles src/index.html, src/app.js, src/style.css and avatars/* into src/assets.js (imported by the Worker).
// Usage: node scripts/build-assets.mjs
import fs from "node:fs"; import path from "node:path"; import crypto from "node:crypto";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const rd = p => fs.readFileSync(path.join(root, p), "utf8");

// emoji avatars for the 10 animal slots (humans) and the built-in AI "ching"
const EMO = { Elephant: ["🐘", "#9aa7c7"], Lion: ["🦁", "#f2c14e"], Tiger: ["🐯", "#f39c4a"], Leopard: ["🐆", "#d9a35b"], Wolf: ["🐺", "#8d99ae"],
  Dog: ["🐶", "#c8a27a"], Cat: ["🐱", "#f7b2bd"], Mouse: ["🐭", "#bfc8d6"], Chicken: ["🐔", "#f6d365"], Duck: ["🦆", "#7fc8a9"], ching: ["🍓", "#ff8fb8"] };
const AVATARS = {}, AVATAR_BIN = {};
for (const [k, [e, c]] of Object.entries(EMO))
  AVATARS[k] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><circle cx="32" cy="32" r="32" fill="${c}"/><text x="32" y="43" font-size="34" text-anchor="middle">${e}</text></svg>`;

// avatars/<slot>.svg | .webp | .png | .jpg  (bitmaps win over svg of the same name)
const MIME = { ".webp": "image/webp", ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg" };
const dir = path.join(root, "avatars");
for (const f of fs.existsSync(dir) ? fs.readdirSync(dir) : []) {
  const ext = path.extname(f).toLowerCase(), name = path.basename(f, path.extname(f));
  if (!/^[A-Za-z]+$/.test(name)) continue;
  if (ext === ".svg") AVATARS[name] = fs.readFileSync(path.join(dir, f), "utf8").trim();
  else if (MIME[ext]) AVATAR_BIN[name] = [MIME[ext], fs.readFileSync(path.join(dir, f)).toString("base64")];
}

const app = rd("src/app.js"), css = rd("src/style.css");
const v = crypto.createHash("sha256").update(app + css).digest("hex").slice(0, 10);   // cache-busting
const html = rd("src/index.html").replace('href="/style.css"', `href="/style.css?v=${v}"`).replace('src="/app.js"', `src="/app.js?v=${v}"`);
const J = x => JSON.stringify(x);
fs.writeFileSync(path.join(root, "src/assets.js"),
  `// GENERATED by scripts/build-assets.mjs — do not edit\nexport const INDEX_HTML = ${J(html)};\nexport const APP_JS = ${J(app)};\nexport const STYLE_CSS = ${J(css)};\nexport const AVATARS = ${J(AVATARS)};\nexport const AVATAR_BIN = ${J(AVATAR_BIN)};\n`);
console.log(`assets.js written (svg: ${Object.keys(AVATARS).length}, bitmap: ${Object.keys(AVATAR_BIN).length}, v=${v})`);
